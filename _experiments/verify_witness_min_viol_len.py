import argparse
import sys
from pathlib import Path

# verify_minimality.py lives in the same directory as this script
sys.path.insert(0, str(Path(__file__).parent))
from verify_minimality import verify_witness_main


def main() -> None:
    ap = argparse.ArgumentParser(
        description=(
            "Compatibility wrapper. Witness verification logic is merged into "
            "_experiments/verify_minimality.py."
        )
    )
    ap.add_argument(
        "--input",
        required=True,
        metavar="FILE",
        help="Input JSON generated by _experiments/verify_minimality.py",
    )
    ap.add_argument(
        "--T",
        type=int,
        default=None,
        metavar="N",
        help="Length bound for recheck (default: parse from json_cache path, else 60).",
    )
    ap.add_argument(
        "--output",
        default=None,
        metavar="FILE",
        help="Output report JSON path (default: _results/verify_witness_report.json).",
    )
    args = ap.parse_args()
    verify_witness_main(input_path=args.input, T=args.T, output_path=args.output)


if __name__ == "__main__":
    main()
